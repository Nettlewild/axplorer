"""Compare several PatternBoost runs in a single figure.

Usage:
    python plot_experiments.py <dir> [<dir> ...] [--labels A B ...] [--optimum 46] [--out comparison.png]

Each <dir> is either a run folder (checkpoint/<exp_name>/<exp_id>) containing
metrics.csv, or any parent folder: every metrics.csv found below it is treated
as a separate experiment.

The figure has four panels:
    1. max reward per epoch
    2. number of local searches needed to reach the optimum
    3. number of valid samples generated per epoch
    4. FLOPs per epoch

Expected metrics.csv columns (missing ones are skipped with a warning):
    epoch, max, num_local_searches, num_valid, flops
If num_valid is missing it is derived as num_local_searches - num_invalid.
If num_local_searches is missing, num_samples_from_model from params.pkl is used.
The optimum is taken from --optimum, otherwise from src/envs/cycle_optimums.txt
for "square" runs (using N from params.pkl).
"""
import argparse
import pickle
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

ROOT = Path(__file__).resolve().parent
CYCLE_OPTIMUMS = ROOT / "src" / "envs" / "cycle_optimums.txt"


def find_runs(dirs):
    runs = []
    for d in dirs:
        d = Path(d)
        if (d / "metrics.csv").is_file():
            runs.append(d)
        else:
            found = sorted(p.parent for p in d.rglob("metrics.csv"))
            if not found:
                print(f"warning: no metrics.csv found in {d}")
            runs.extend(found)
    return runs


def load_params(run_dir):
    path = run_dir / "params.pkl"
    if not path.is_file():
        return None
    try:
        with open(path, "rb") as f:
            return pickle.load(f)
    except Exception as e:
        print(f"warning: cannot read {path}: {e}")
        return None


def known_optimum(params):
    if params is None or getattr(params, "env_name", None) != "square" or not CYCLE_OPTIMUMS.is_file():
        return None
    values = [int(v) for v in CYCLE_OPTIMUMS.read_text().split(",") if v.strip()]
    n = getattr(params, "N", None)
    return values[n - 1] if n is not None and 1 <= n <= len(values) else None


def default_label(run_dir):
    # checkpoint/<exp_name>/<exp_id> -> "<exp_name>/<exp_id>"
    return f"{run_dir.parent.name}/{run_dir.name}"


def load_run(run_dir, label, optimum_override):
    df = pd.read_csv(run_dir / "metrics.csv").sort_values("epoch").reset_index(drop=True)
    params = load_params(run_dir)

    if "num_local_searches" not in df.columns and params is not None and hasattr(params, "num_samples_from_model"):
        # every sample generated by the model goes through local search; epoch 0 is the initial dataset
        df["num_local_searches"] = [0 if e == 0 else params.num_samples_from_model for e in df["epoch"]]
    if "num_valid" not in df.columns and {"num_local_searches", "num_invalid"} <= set(df.columns):
        # epochs without generated samples (epoch 0) have no meaningful count
        df["num_valid"] = (df["num_local_searches"] - df["num_invalid"]).where(df["num_local_searches"] > 0)

    optimum = optimum_override if optimum_override is not None else known_optimum(params)
    return {"label": label, "df": df, "optimum": optimum}


def searches_to_optimum(run):
    """Cumulative local searches up to the first epoch whose max reward reaches the optimum.
    Returns (value, reached); if never reached, value is the total number of searches done."""
    df, optimum = run["df"], run["optimum"]
    if optimum is None or "max" not in df.columns or "num_local_searches" not in df.columns:
        return None, False
    cumulative = df["num_local_searches"].fillna(0).cumsum()
    hit = df.index[df["max"] >= optimum]
    if len(hit) > 0:
        return cumulative[hit[0]], True
    return cumulative.iloc[-1], False


def missing_panel(ax, title, column):
    ax.set_title(title)
    ax.text(0.5, 0.5, f"column '{column}' not found in any metrics.csv", ha="center", va="center", transform=ax.transAxes, color="gray")
    ax.set_xticks([])
    ax.set_yticks([])


def plot_per_epoch(ax, runs, column, title, ylabel, colors, logy=False):
    plotted = False
    for run, color in zip(runs, colors):
        df = run["df"]
        if column in df.columns:
            ax.plot(df["epoch"], df[column], marker="o", markersize=3, color=color, label=run["label"])
            plotted = True
    if not plotted:
        missing_panel(ax, title, column)
        return False
    ax.set_title(title)
    ax.set_xlabel("Epoch")
    ax.set_ylabel(ylabel)
    if logy:
        ax.set_yscale("log")
    ax.grid(True, alpha=0.3)
    return True


def plot_max_reward(ax, runs, colors):
    if not plot_per_epoch(ax, runs, "max", "Max reward per epoch", "Max reward", colors):
        return
    for optimum in sorted({r["optimum"] for r in runs if r["optimum"] is not None}):
        ax.axhline(optimum, color="black", linestyle="--", linewidth=1, label=f"Optimum ({optimum})")


def plot_searches_to_optimum(ax, runs, colors):
    title = "Local searches to reach the optimum"
    values = [searches_to_optimum(r) for r in runs]
    if all(v is None for v, _ in values):
        missing_panel(ax, title, "num_local_searches / optimum")
        return
    x = range(len(runs))
    for i, ((value, reached), run, color) in enumerate(zip(values, runs, colors)):
        if value is None:
            ax.text(i, 0, "n/a", ha="center", va="bottom", color="gray")
            continue
        ax.bar(i, value, color=color if reached else "none", edgecolor=color, hatch=None if reached else "//")
        ax.text(i, value, f"{value:,.0f}" if reached else f"not reached\n(>{value:,.0f})", ha="center", va="bottom", fontsize=8)
    ax.set_xticks(list(x))
    ax.set_xticklabels([r["label"] for r in runs], rotation=30, ha="right", fontsize=8)
    ax.set_title(title)
    ax.set_ylabel("Cumulative local searches")
    ax.set_ylim(top=1.15 * max(v for v, _ in values if v is not None) or 1)
    ax.grid(True, axis="y", alpha=0.3)


def main():
    parser = argparse.ArgumentParser(description="Plot metrics.csv of several experiments in a single figure.")
    parser.add_argument("dirs", nargs="+", help="run folders or parent folders containing metrics.csv")
    parser.add_argument("--labels", nargs="+", default=None, help="legend labels, one per experiment found")
    parser.add_argument("--optimum", type=float, default=None, help="optimum reward (overrides the one read from params.pkl)")
    parser.add_argument("--out", type=str, default="experiments_comparison.png", help="output image path")
    args = parser.parse_args()

    run_dirs = find_runs(args.dirs)
    if not run_dirs:
        raise SystemExit("no experiments found")
    if args.labels is not None and len(args.labels) != len(run_dirs):
        raise SystemExit(f"got {len(args.labels)} labels for {len(run_dirs)} experiments: {[str(d) for d in run_dirs]}")
    labels = args.labels or [default_label(d) for d in run_dirs]

    runs = [load_run(d, label, args.optimum) for d, label in zip(run_dirs, labels)]
    for d, run in zip(run_dirs, runs):
        print(f"{run['label']}: {len(run['df'])} epochs, optimum={run['optimum']}  ({d})")

    colors = plt.get_cmap("tab10").colors * (len(runs) // 10 + 1)
    fig, axes = plt.subplots(2, 2, figsize=(14, 10))
    plot_max_reward(axes[0, 0], runs, colors)
    plot_searches_to_optimum(axes[0, 1], runs, colors)
    plot_per_epoch(axes[1, 0], runs, "num_valid", "Valid samples generated per epoch", "Valid samples", colors)
    plot_per_epoch(axes[1, 1], runs, "flops", "FLOPs per epoch", "FLOPs", colors, logy=True)

    handles, legend_labels = axes[0, 0].get_legend_handles_labels()
    if handles:
        fig.legend(handles, legend_labels, loc="lower center", ncol=min(len(handles), 4), frameon=False)
    fig.suptitle("Experiment comparison")
    fig.tight_layout(rect=(0, 0.06, 1, 0.97))
    fig.savefig(args.out, dpi=150)
    print(f"saved {args.out}")


if __name__ == "__main__":
    main()
